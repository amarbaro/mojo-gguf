"""Generate src/hfconv/chk_table.mojo from the pinned converter: the pre-tokenizer check text, its normalized
forms, and the chkhsh -> tokenizer.ggml.pre table that get_vocab_base_pre in conversion/base.py carries.

    gen-hf-table.py LLAMACPP_DIR OUT.mojo

Output is a pure function of conversion/base.py and the Python Unicode database. hf-update only ever normalizes
pieces of that one text, so NFC/NFD/NFKC/NFKD/lowercase are emitted as per-character folds of the characters it
contains plus printable ASCII (checked here to compose to the whole-string result): the Mojo side needs no Unicode
tables, and any other character folds to itself.
Fails loudly (FAIL gen-hf-table: ...) when base.py no longer has the shape we read.
"""
import re
import sys
import unicodedata

if len(sys.argv) != 3:
    sys.exit("usage: gen-hf-table.py LLAMACPP_DIR OUT.mojo")


def fail(msg):
    sys.exit(f"FAIL gen-hf-table: {msg}")


src = open(f"{sys.argv[1]}/conversion/base.py").read()
if "def get_vocab_base_pre" not in src:
    fail("conversion/base.py has no get_vocab_base_pre")
body = src[src.index("def get_vocab_base_pre"):]
m = re.search(r"\n\s+chktxt = (.+)\n", body)
if not m:
    fail("chktxt assignment not found")
chktxt = eval(m.group(1))
rows = re.findall(r'if chkhsh == "([0-9a-f]{64})":(?:\s*#[^\n]*)*\s*res = "([^"]+)"', body)
if len(rows) != body.count('if chkhsh == "'):
    fail(f"{len(rows)} rows parsed, {body.count('if chkhsh == ')} chkhsh tests present")
table = {}
for h, n in rows:  # the converter tests with consecutive `if`s: the last matching row wins
    table[h] = n


def lit(s):
    out = []
    for c in s:
        o = ord(c)
        if c == "\n":
            out.append("\\n")
        elif c == "\t":
            out.append("\\t")
        elif c in '"\\':
            out.append("\\" + c)
        elif 0x20 <= o < 0x7F:
            out.append(c)
        elif o < 0x10000 and not 0xD800 <= o < 0xE000:
            out.append(f"\\u{o:04x}")
        elif o >= 0x10000:
            out.append(f"\\U{o:08x}")
        else:
            fail(f"unencodable codepoint {o:#x}")
    return '"' + "".join(out) + '"'


with open(sys.argv[2], "w") as f:
    f.write("# GENERATED by tools/gen-hf-table.py from the pinned conversion/base.py. Do not edit.\n")
    f.write(f"comptime CHKTXT = {lit(chktxt)}\n")
    folds = [
        ("NFC", lambda t: unicodedata.normalize("NFC", t)),
        ("NFD", lambda t: unicodedata.normalize("NFD", t)),
        ("NFKC", lambda t: unicodedata.normalize("NFKC", t)),
        ("NFKD", lambda t: unicodedata.normalize("NFKD", t)),
        ("LOWER", lambda t: t.lower()),
    ]
    for i, (name, fn) in enumerate(folds):
        f.write(f"comptime FOLD_{name} = {i}\n")
        if "".join(fn(c) for c in chktxt) != fn(chktxt):
            fail(f"{name} of chktxt is not the concatenation of its per-character folds")
    f.write("\ndef fold_char(form: Int, cp: Int) -> String:\n")
    f.write('    """Replacement text for codepoint cp under a normalization form, "" when it is unchanged."""\n')
    for i, (name, fn) in enumerate(folds):
        diff = [(c, fn(c)) for c in sorted(set(chktxt) | {chr(o) for o in range(0x20, 0x7F)}) if fn(c) != c]
        if diff:
            f.write(f"    if form == FOLD_{name}:\n")
            for c, r in diff:
                f.write(f"        if cp == {ord(c)}:\n            return {lit(r)}\n")
    f.write('    return ""\n\n')
    f.write("def pre_name(chkhsh: String) -> String:\n")
    f.write('    """tokenizer.ggml.pre for a chkhsh, or "unknown"."""\n')
    for h, n in table.items():
        f.write(f'    if chkhsh == "{h}":\n        return "{n}"\n')
    f.write('    return "unknown"\n')
print(f"gen-hf-table: {len(table)} hashes from {len(rows)} rows, chktxt {len(chktxt.encode())} bytes -> {sys.argv[2]}")
