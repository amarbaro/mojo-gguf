"""Generate src/ggufx/nonprint.mojo: the code point ranges str.isprintable() rejects, which repr() escapes.

    gen-nonprint.py OUT.mojo        (run with the oracle python, .venv/bin/python: its Unicode version is the reference)

A pure function of the Python build: no timestamps. Surrogates are left out (a Mojo String cannot hold one)."""
import sys, unicodedata

ranges, start = [], None
for cp in range(0x110000):
    bad = not (0xD800 <= cp < 0xE000) and not chr(cp).isprintable()
    if bad and start is None:
        start = cp
    elif not bad and start is not None:
        ranges.append((start, cp - 1))
        start = None
if start is not None:
    ranges.append((start, 0x10FFFF))
body = "".join("%06x%06x" % r for r in ranges)
open(sys.argv[1], "w").write(f'''# Generated by tools/gen-nonprint.py. Do not edit by hand; rerun the generator.
# source: Python {sys.version.split()[0]}, Unicode {unicodedata.unidata_version}: {len(ranges)} ranges of code points str.isprintable() rejects,
# 12 hex digits each (first, last), sorted.
comptime _RANGES = "{body}"


def _hex6(b: Span[UInt8, _], at: Int) -> Int:
    var v = 0
    for k in range(at, at + 6):
        var c = Int(b[k])
        v = v * 16 + (c - 48 if c < 58 else c - 87)
    return v


def nonprintable(cp: Int) -> Bool:
    """True when Python's repr() escapes cp (str.isprintable() is False)."""
    var b = _RANGES.as_bytes()
    var lo = 0
    var hi = len(b) // 12
    while lo < hi:
        var mid = (lo + hi) // 2
        if _hex6(b, mid * 12 + 6) < cp:
            lo = mid + 1
        else:
            hi = mid
    return lo < len(b) // 12 and _hex6(b, lo * 12) <= cp
''')
