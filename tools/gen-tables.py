"""Generate the U2 Mojo tables from gguf-py: enum constants, name tables, per-arch tensor-name rows.

    gen-tables.py GGUFPY_DIR OUT_DIR

Writes OUT_DIR/consts.mojo and OUT_DIR/tensor_map.mojo. Output is a pure function of the input: no timestamps,
no paths, sorted tables. Fails loudly (FAIL gen-tables: ...) on anything the Mojo side does not model.

tensor_map rows mirror gguf-py TensorNameMap.__init__ as templates: a row is (hf_pre, hf_post, out_pre, out_post,
is_block, out_bid). A block row's key is hf_pre + bid + hf_post; its value is out_pre + bid + out_post when out_bid,
else out_pre (out_post empty). Mojo expands bid for any n_blocks.
TensorNameMap.block_mappings_cfg is a class dict that __init__ updates in place, so each arch starts from a pristine
copy here (the oracle runs the same five arches in one process, where the order happens not to matter).
"""
import sys
from pathlib import Path

if len(sys.argv) != 3:
    sys.exit("usage: gen-tables.py GGUFPY_DIR OUT_DIR")
sys.path.insert(0, sys.argv[1])
from gguf import constants as C
from gguf.tensor_mapping import TensorNameMap

MAPPED_ARCHS = ["LLAMA", "QWEN2", "QWEN35", "QWEN35MOE", "QWEN4EXP"]
PRISTINE_BLOCK = dict(TensorNameMap.block_mappings_cfg)
CONFLICT_CHECK_BLOCKS = 128


def fail(msg):
    sys.exit(f"FAIL gen-tables: {msg}")


def lit(s):
    if not all(0x20 <= ord(c) <= 0x7E and c not in '"\\' for c in s):
        fail(f"string not plain printable ASCII: {s!r}")
    return f'"{s}"'


def keys(cls, pre=""):
    out = {}
    for k, v in vars(cls).items():
        if k.startswith("_"):
            continue
        if isinstance(v, type):
            out.update(keys(v, pre + k + "."))
        elif isinstance(v, str):
            out[pre + k] = v
    return out


def sorted_unique(pairs, what):
    names = [p[0] for p in pairs]
    if len(set(names)) != len(names):
        fail(f"duplicate key in {what}")
    return sorted(pairs, key=lambda p: p[0])


def table(name, ret, items):
    return [f"def {name}() -> {ret}:", "    return ["] + [f"        {i}," for i in items] + ["    ]", ""]


def consts_mojo():
    out = ["# Generated by tools/gen-tables.py from gguf-py constants.py. Do not edit.", ""]
    for enum, prefix in [(C.GGUFValueType, "GGUF_VALUE_"), (C.GGMLQuantizationType, "GGML_TYPE_"),
                         (C.MODEL_ARCH, "MODEL_ARCH_"), (C.MODEL_TENSOR, "MODEL_TENSOR_")]:
        for m in enum:
            out.append(f"comptime {prefix}{m.name} = {int(m.value)}")
        out.append("")

    vt = sorted_unique([(t.name, int(t)) for t in C.GGUFValueType], "value_types")
    out += table("value_types", "List[Tuple[String, Int]]", [f"({lit(n)}, {v})" for n, v in vt])

    qt = sorted_unique([(t.name, int(t)) for t in C.GGMLQuantizationType], "quant_types")
    out += table("quant_types", "List[Tuple[String, Int]]", [f"({lit(n)}, {v})" for n, v in qt])

    qs = []
    for t in C.GGML_QUANT_SIZES:
        sz = list(C.GGML_QUANT_SIZES[t])
        if len(sz) != 2:
            fail(f"quant size of {t.name} has {len(sz)} fields")
        qs.append((t.name, sz))
    qs = sorted_unique(qs, "quant_sizes")
    out += table("quant_sizes", "List[Tuple[String, Int, Int]]",
                 [f"({lit(n)}, {a}, {b})" for n, (a, b) in qs])

    an = sorted_unique([(a.name, C.MODEL_ARCH_NAMES[a]) for a in C.MODEL_ARCH], "arch_names")
    out += table("arch_names", "List[Tuple[String, String]]", [f"({lit(n)}, {lit(v)})" for n, v in an])

    tn = sorted_unique([(t.name, C.TENSOR_NAMES[t]) for t in C.MODEL_TENSOR if t in C.TENSOR_NAMES], "tensor_names")
    out += table("tensor_names", "List[Tuple[String, String]]", [f"({lit(n)}, {lit(v)})" for n, v in tn])

    # one row per (arch, tensor), arches sorted, tensors in MODEL_TENSORS order: Mojo has no nested literal lists
    at = sorted_unique([(C.MODEL_ARCH_NAMES[a], [t.name for t in C.MODEL_TENSORS[a]]) for a in C.MODEL_TENSORS],
                       "arch_tensors")
    if any(not v for _, v in at):
        fail("arch with an empty tensor list")
    out += table("arch_tensors", "List[Tuple[String, String]]",
                 [f"({lit(n)}, {lit(t)})" for n, v in at for t in v])

    kv = sorted_unique(list(keys(C.Keys).items()), "keys")
    out += table("gguf_keys", "List[Tuple[String, String]]", [f"({lit(n)}, {lit(v)})" for n, v in kv])
    return out[:-1]


def arch_rows(arch):
    """Ordered, de-duplicated rows of TensorNameMap(arch, n) as templates."""
    rows = {}

    def put(hf, out):
        # a key with {bid} expands per block; one without is literal, and its value must not depend on the block
        if "{bid}" in hf:
            if hf.count("{bid}") != 1 or out.count("{bid}") > 1:
                fail(f"{arch}: block key needs one {{bid}}, value at most one: {hf!r} -> {out!r}")
            hf_pre, hf_post = hf.split("{bid}")
            if "{bid}" in out:
                out_pre, out_post = out.split("{bid}")
                rows[(hf_pre, hf_post, out_pre, out_post, True, True)] = None
            else:
                rows[(hf_pre, hf_post, out, "", True, False)] = None
        else:
            if "{bid}" in out:
                fail(f"{arch}: literal key with block-dependent value: {hf!r} -> {out!r}")
            rows[(hf, "", out, "", False, False)] = None

    for tensor, keys_ in TensorNameMap.mappings_cfg.items():
        if tensor not in C.MODEL_TENSORS[arch]:
            continue
        name = C.TENSOR_NAMES[tensor]
        put(name, name)
        for key in keys_:
            put(key, name)

    block_cfg = dict(PRISTINE_BLOCK)
    if arch in TensorNameMap.arch_block_mappings_cfg:
        block_cfg.update(TensorNameMap.arch_block_mappings_cfg[arch])
    for tensor, keys_ in block_cfg.items():
        if tensor not in C.MODEL_TENSORS[arch]:
            continue
        name = C.TENSOR_NAMES[tensor]
        put(name, name)
        for key in keys_:
            put(key, name)
    return list(rows)


def check_conflicts(arch, rows):
    """Two rows may not map one key to two values, or the first-match lookup would differ from dict overwrite."""
    seen = {}
    for bid in range(CONFLICT_CHECK_BLOCKS):
        for hf_pre, hf_post, out_pre, out_post, block, out_bid in rows:
            if block:
                key, val = f"{hf_pre}{bid}{hf_post}", f"{out_pre}{bid if out_bid else ''}{out_post}"
            elif bid == 0:
                key, val = hf_pre, out_pre
            else:
                continue
            if seen.setdefault(key, val) != val:
                fail(f"{arch}: key {key!r} maps to two values ({seen[key]!r}, {val!r})")


def row_lit(r):
    return "(" + ", ".join([lit(r[0]), lit(r[1]), lit(r[2]), lit(r[3]), str(r[4]), str(r[5])]) + ")"


def tensor_map_mojo():
    names = [C.MODEL_ARCH_NAMES[C.MODEL_ARCH[a]] for a in MAPPED_ARCHS]
    out = ["# Generated by tools/gen-tables.py from gguf-py tensor_mapping.py. Do not edit.", "",
           "comptime Row = Tuple[String, String, String, String, Bool, Bool]", "",
           "def mapped_arches() -> List[String]:",
           f"    return [{', '.join(lit(n) for n in names)}]", "",
           "def arch_rows(arch: String) -> List[Row]:"]
    for a, name in zip(MAPPED_ARCHS, names):
        rows = arch_rows(C.MODEL_ARCH[a])
        check_conflicts(name, rows)
        out += [f"    if arch == {lit(name)}:", "        return ["]
        out += [f"            {row_lit(r)}," for r in rows]
        out += ["        ]"]
    out += ["    return []", ""]
    return out


def main():
    out_dir = Path(sys.argv[2])
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "consts.mojo").write_text("\n".join(consts_mojo()) + "\n")
    (out_dir / "tensor_map.mojo").write_text("\n".join(tensor_map_mojo()))


main()
