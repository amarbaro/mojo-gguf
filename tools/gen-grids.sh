#!/usr/bin/env bash
# Regenerate src/ggufx/grids.mojo: the codebook tables of ggml-common.h (pinned llama.cpp) that the IQ dequant rows
# index. usage: tools/gen-grids.sh [GGML_COMMON_H]   (writes src/ggufx/grids.mojo, shell + awk only)
set -euo pipefail
H=${1:-${LLAMACPP:-.work/llama.cpp}/ggml/src/ggml-common.h}
OUT=$(dirname "$0")/../src/ggufx/grids.mojo
tbl() {  # name -> comma-joined values of GGML_TABLE_BEGIN(type, name, n) .. GGML_TABLE_END
  awk -v n="$1" '$0 ~ "GGML_TABLE_BEGIN\\(.*, " n "," {on=1; next} on && /GGML_TABLE_END/ {exit} on' "$H" |
    grep -o '0x[0-9a-f]*\|-\?[0-9]\+' | paste -sd, | sed 's/,/, /g'
}
need() { [ "$(tbl "$1" | tr ',' '\n' | wc -l)" = "$2" ] || { echo "FAIL gen-grids: $1 has not $2 values" >&2; exit 1; }; }
need iq2xxs_grid 256; need iq1s_grid 2048; need kvalues_iq4nl 16
{
  echo '"""Codebooks of the IQ quant types, generated by tools/gen-grids.sh from ggml-common.h: do not edit."""'
  echo 'from std.collections import Array'
  echo
  echo "# 8 grid bytes per entry, byte j in bits 8j..8j+7"
  echo "comptime IQ2XXS_GRID: Array[UInt64, 256] = [$(tbl iq2xxs_grid)]"
  echo "comptime IQ1S_GRID: Array[UInt64, 2048] = [$(tbl iq1s_grid)]"
  echo "comptime KVALUES_IQ4NL: Array[Int32, 16] = [$(tbl kvalues_iq4nl)]"
} > "$OUT"
echo "wrote $OUT ($(wc -c < "$OUT") bytes)"
